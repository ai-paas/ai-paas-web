import { describe, it, expect } from 'vitest';
import { formatCount } from './count';

describe('formatCount', () => {
  // ============================================
  // 1000 미만: 변환 없이 그대로 출력
  // ============================================
  describe('1000 미만 입력', () => {
    it.each([
      [0, '0'],
      [500, '500'],
      [999, '999'],
    ])('%i은(는) 단위 없이 "%s"로 출력한다', (input, expected) => {
      expect(formatCount(input)).toBe(expected);
    });
  });

  // ============================================
  // K 단위 (1,000 이상)
  // ============================================
  describe('K 단위 변환', () => {
    it.each([
      [1000, '1K'],
      [1500, '1.5K'],
      [2000, '2K'],
    ])('%i은(는) "%s"로 출력한다', (input, expected) => {
      expect(formatCount(input)).toBe(expected);
    });
  });

  // ============================================
  // M / B / T 단위 (1e6, 1e9, 1e12)
  // ============================================
  describe('M/B/T 단위 변환', () => {
    it.each([
      [1_000_000, '1M'],
      [2_500_000, '2.5M'],
      [1_000_000_000, '1B'],
      [1_000_000_000_000, '1T'],
    ])('%i은(는) "%s"로 출력한다', (input, expected) => {
      expect(formatCount(input)).toBe(expected);
    });
  });

  // ============================================
  // 단위 상한 (T 초과)
  // ============================================
  describe('단위 상한 동작', () => {
    it('1e15는 T가 마지막 단위이므로 "1000T"로 출력한다', () => {
      expect(formatCount(1e15)).toBe('1000T');
    });

    it('1e18은 "1000000T"로 출력한다 (T 단위에서 숫자가 계속 커진다)', () => {
      expect(formatCount(1e18)).toBe('1000000T');
    });
  });

  // ============================================
  // 특성화 테스트: 단위 경계 직전 값의 올림 현상
  // ============================================
  describe('단위 경계 직전 값 (특성화)', () => {
    // 버그 의심 — 팀 확인 필요:
    // 999999 / 1000 = 999.999 인데 toFixed(1) 반올림으로 "1000.0K"가 된다.
    // 사용자 기대값은 "999.9K" 또는 "1M"일 가능성이 높다.
    it('999999는 현재 구현에서 "1000.0K"로 출력한다', () => {
      expect(formatCount(999999)).toBe('1000.0K');
    });

    // 버그 의심 — 팀 확인 필요: 위와 동일한 원인으로 M 단위에서도 재현된다.
    it('999999999는 현재 구현에서 "1000.0M"로 출력한다', () => {
      expect(formatCount(999_999_999)).toBe('1000.0M');
    });
  });

  // ============================================
  // 반올림 경계 (toFixed(1) 동작)
  // ============================================
  describe('반올림 경계', () => {
    it.each([
      [1049, '1.0K'],
      [1050, '1.1K'],
      [1099, '1.1K'],
      [1999, '2.0K'],
    ])('%i은(는) "%s"로 출력한다', (input, expected) => {
      expect(formatCount(input)).toBe(expected);
    });

    it('소수점이 정확히 0으로 떨어지지 않으면 "2K"가 아닌 "2.0K"처럼 뒤에 .0이 붙는다', () => {
      // 특성화: 1999 → 1.999 → toFixed(1) → "2.0" (정수 표기 "2"와 불일치)
      expect(formatCount(1999)).toBe('2.0K');
      expect(formatCount(2000)).toBe('2K');
    });
  });

  // ============================================
  // 음수·소수 입력 (특성화)
  // ============================================
  describe('음수·소수 입력', () => {
    it.each([
      [-5, '-5'],
      [-1500, '-1500'],
    ])('음수 %i은(는) 단위 변환 없이 "%s"로 출력한다', (input, expected) => {
      // 특성화: 음수는 항상 1000 미만 분기로 빠져 단위 변환이 적용되지 않는다
      expect(formatCount(input)).toBe(expected);
    });

    it.each([
      [0.5, '0.5'],
      [999.5, '999.5'],
      [1234.5, '1.2K'],
    ])('소수 %d은(는) "%s"로 출력한다', (input, expected) => {
      expect(formatCount(input)).toBe(expected);
    });
  });
});
