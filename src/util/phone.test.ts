import { describe, it, expect } from 'vitest';
import { formatPhone } from './phone';

describe('formatPhone', () => {
  // ============================================
  // 빈 입력
  // ============================================
  describe('빈 입력', () => {
    it('undefined면 빈 문자열을 반환한다', () => {
      expect(formatPhone(undefined)).toBe('');
    });

    it('빈 문자열이면 빈 문자열을 반환한다', () => {
      expect(formatPhone('')).toBe('');
    });
  });

  // ============================================
  // 02 지역번호(서울)
  // ============================================
  describe('02 지역번호(서울)', () => {
    it.each([
      ['0212345678', '02-1234-5678'],
      ['021234567', '02-123-4567'],
    ])('%s → %s', (input, expected) => {
      expect(formatPhone(input)).toBe(expected);
    });
  });

  // ============================================
  // 휴대폰/3자리 지역번호
  // ============================================
  describe('휴대폰/3자리 지역번호', () => {
    it.each([
      ['01012345678', '010-1234-5678'],
      ['0111234567', '011-123-4567'],
      ['0311234567', '031-123-4567'],
      ['0631234567', '063-123-4567'],
    ])('%s → %s', (input, expected) => {
      expect(formatPhone(input)).toBe(expected);
    });
  });

  // ============================================
  // 대표번호(8자리)
  // ============================================
  describe('대표번호(8자리)', () => {
    it.each([
      ['15001234', '1500-1234'],
      ['15881234', '1588-1234'],
      ['16441234', '1644-1234'],
      ['18991234', '1899-1234'],
    ])('15xx~18xx 대역 %s → %s', (input, expected) => {
      expect(formatPhone(input)).toBe(expected);
    });

    it.each([['14991234'], ['19001234']])('대역 밖 %s는 원문을 반환한다', (input) => {
      expect(formatPhone(input)).toBe(input);
    });
  });

  // ============================================
  // 하이픈·공백·괄호 섞인 입력
  // ============================================
  describe('구분자 섞인 입력', () => {
    it.each([
      ['(02) 1234-5678', '02-1234-5678'],
      ['010 1234 5678', '010-1234-5678'],
      ['031-123-4567', '031-123-4567'],
      ['1588 1234', '1588-1234'],
    ])("'%s' → '%s' (숫자만 추출 후 포맷)", (input, expected) => {
      expect(formatPhone(input)).toBe(expected);
    });
  });

  // ============================================
  // maskMiddle 옵션
  // ============================================
  describe('maskMiddle 옵션', () => {
    it.each([
      ['01012345678', '010-****-5678'],
      ['0212345678', '02-****-5678'],
      ['021234567', '02-***-4567'],
      ['0311234567', '031-***-4567'],
    ])('%s → %s (가운데 그룹만 마스킹)', (input, expected) => {
      expect(formatPhone(input, { maskMiddle: true })).toBe(expected);
    });

    it('대표번호는 maskMiddle을 지정해도 마스킹하지 않는다', () => {
      // 특성화: 대표번호 분기는 fmt()를 거치지 않아 maskMiddle 옵션이 무시된다.
      // 공개 번호라 의도적일 수 있으나 옵션 무시가 의도인지 버그 의심 — 팀 확인 필요
      expect(formatPhone('15881234', { maskMiddle: true })).toBe('1588-1234');
    });

    it('형식 모호로 원문을 반환할 때도 maskMiddle이 적용되지 않는다', () => {
      // 특성화: 원문 반환 경로는 마스킹 없이 숫자가 그대로 노출된다 — 팀 확인 필요
      expect(formatPhone('1234567', { maskMiddle: true })).toBe('1234567');
    });
  });

  // ============================================
  // 형식 모호 입력 → 원문 반환
  // ============================================
  describe('형식 모호 입력(원문 반환)', () => {
    it.each([
      ['7자리', '1234567'],
      ['12자리', '021234567890'],
      ['13자리', '0101234567890'],
    ])('%s 숫자는 원문을 반환한다', (_label, input) => {
      expect(formatPhone(input)).toBe(input);
    });

    it('원문 반환 시 구분자를 제거하지 않고 입력 그대로 반환한다', () => {
      expect(formatPhone('123-4567')).toBe('123-4567');
    });
  });

  // ============================================
  // 02로 시작하는 11자리 (특성화)
  // ============================================
  describe('02로 시작하는 11자리 (특성화)', () => {
    it("'02123456789'는 02 분기를 지나쳐 3-4-4 형식(021-2345-6789)으로 포맷된다", () => {
      // 버그 의심 — 팀 확인 필요: 02 블록은 9/10자리만 처리하므로 02로 시작하는
      // 11자리는 일반 11자리 분기로 떨어져 존재하지 않는 지역번호 '021'이 앞자리가 된다.
      // (유효하지 않은 번호를 원문 반환하지 않고 021-xxxx-xxxx로 포맷)
      expect(formatPhone('02123456789')).toBe('021-2345-6789');
    });
  });
});
